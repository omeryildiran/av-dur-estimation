"""Bias (c, d) recovery: sigma_A free (bias_recovery.json) vs tied to the unimodal auditory block
(bias_recovery_sa.json, --scenarios), on the same simulated participants, 70 trials per condition.

    python analysis/overnight_sims/bias_analyse.py

Recovery is scored against the spread of the true values: an RMSE above the true SD is worse than
guessing the mean for everyone.
"""

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
RES = Path(__file__).resolve().parent / "results"
BUDGET = "70"


def rows():
    out = []
    sources = [("sigma_A free", json.loads((RES / "bias_recovery.json").read_text()), None)]
    if (RES / "bias_recovery_sa.json").exists():
        sa = json.loads((RES / "bias_recovery_sa.json").read_text())
        names = sorted({k for r in sa for k in r.get("scenarios", {})})
        sources += [(f"sigma_A known, log err {n[2:]}", sa, n) for n in names]
    for label, results, key in sources:
        for r in results:
            block = r["budgets"] if key is None else r["scenarios"][key]["budgets"]
            if BUDGET not in block:
                continue
            c1, c2, d = r["bias"]
            for model, variants in block[BUDGET]["fits"].items():
                for variant, f in variants.items():
                    p = f["params"]
                    out.append(dict(scenario=label, gen=r["gen"], it=r["iter"], model=model, variant=variant, aic=f["aic"],
                                    c1=p.get("c1"), c2=p.get("c2"), d=p.get("d"), pc=p.get("pc"), t_c1=c1, t_c2=c2, t_d=d,
                                    t_pc=r["truth"][3] if r["gen"] == "ci" else np.nan))
    df = pd.DataFrame(out)
    both = df.groupby(["gen", "it"]).scenario.nunique()               # participants in every scenario (paired)
    keep = both[both == df.scenario.nunique()].index
    return df.set_index(["gen", "it"]).loc[keep].reset_index()


def rec(g, est, true):
    e, t = g[est].astype(float), g[true].astype(float)
    return pd.Series(dict(r=np.corrcoef(e, t)[0, 1], rmse=np.sqrt(np.mean((e - t) ** 2)), true_sd=t.std(),
                          mean_err=np.mean(e - t), at_bound=np.mean(np.abs(e) > 0.78), n=len(g)))


SCEN_ORDER = ["sigma_A free", "sigma_A known, log err 0.15", "sigma_A known, log err 0.05"]
SCEN_LABEL = {"sigma_A free": r"$\sigma_A$ free", "sigma_A known, log err 0.15": r"$\sigma_A$ known (log error 0.15)",
              "sigma_A known, log err 0.05": r"$\sigma_A$ known (log error 0.05)"}
GEN_LABEL = {"ci": "causal inference", "fusion": "fusion", "switch": "switching"}


def figures(df, folder):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
    own = df[df.model == df.gen]
    gens = ["ci", "fusion", "switch"]

    def scatter(ax, g, est, true, lim):
        ax.plot(lim, lim, color="0.7", lw=0.8)
        ax.scatter(g[true], g[est].clip(*lim), s=7, alpha=0.6, color="tab:blue", lw=0)
        r, rmse = np.corrcoef(g[est], g[true])[0, 1], np.sqrt(np.mean((g[est] - g[true]) ** 2))
        ax.text(0.03, 0.97, f"r = {r:.2f}\nRMSE = {rmse:.2f}\nSD true = {g[true].std():.2f}", transform=ax.transAxes,
                va="top", fontsize=8, bbox=dict(facecolor="white", edgecolor="none", alpha=0.8, pad=1))
        ax.set(xlim=lim, ylim=lim)

    fig, axes = plt.subplots(3, 3, figsize=(8.2, 8), sharex=True, sharey=True)
    for i, scn in enumerate(SCEN_ORDER):
        for j, gen in enumerate(gens):
            scatter(axes[i, j], own[(own.scenario == scn) & (own.gen == gen) & (own.variant == "bias")], "d", "t_d", (-0.85, 0.85))
            if i == 0:
                axes[i, j].set_title(f"generated by {GEN_LABEL[gen]}")
            if j == 0:
                axes[i, j].set_ylabel(f"{SCEN_LABEL[scn]}\nrecovered d")
            if i == 2:
                axes[i, j].set_xlabel("true d")
    fig.tight_layout()
    fig.savefig(folder / "fig_bias_d.pdf")
    plt.close(fig)

    fig, axes = plt.subplots(2, 3, figsize=(8.2, 5.4), sharex=True, sharey=True)
    scn = "sigma_A known, log err 0.15"
    for i, (p, name) in enumerate((("c1", "$c$ low noise"), ("c2", "$c$ high noise"))):
        for j, gen in enumerate(gens):
            scatter(axes[i, j], own[(own.scenario == scn) & (own.gen == gen) & (own.variant == "bias")], p, "t_" + p, (-0.85, 0.85))
            if i == 0:
                axes[i, j].set_title(f"generated by {GEN_LABEL[gen]}")
            if j == 0:
                axes[i, j].set_ylabel(f"recovered {name}")
            if i == 1:
                axes[i, j].set_xlabel("true value")
    fig.tight_layout()
    fig.savefig(folder / "fig_bias_c.pdf")
    plt.close(fig)

    fits = (("no bias", ["nobias"]), ("d only", ["d"]), ("c and d", ["bias"]), ("best of all", ["nobias", "d", "bias"]))
    fig, axes = plt.subplots(1, 4, figsize=(9.6, 2.9), sharey=True)
    colors = ["0.65", "tab:blue", "tab:green"]
    for k, (panel, gsel) in enumerate((("causal inference", ["ci"]), ("fusion", ["fusion"]), ("switching", ["switch"]),
                                       ("all", gens))):
        ax = axes[k]
        for s_i, scn in enumerate(SCEN_ORDER):
            vals = []
            for _, sel in fits:
                s = df[(df.scenario == scn) & df.variant.isin(sel) & df.gen.isin(gsel)]
                best = s.loc[s.groupby(["gen", "it"]).aic.idxmin()]
                vals.append(100 * (best.model == best.gen).mean())
            ax.bar(np.arange(4) + (s_i - 1) * 0.27, vals, 0.27, color=colors[s_i], label=SCEN_LABEL[scn])
        ax.set_xticks(np.arange(4))
        ax.set_xticklabels([f for f, _ in fits], rotation=30, ha="right")
        ax.set(title=panel, ylim=(40, 100))
        ax.axhline(100 / 3, color="0.85", lw=0.8)
    axes[0].set_ylabel("right model (AIC), %")
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, frameon=False, fontsize=8, loc="lower center", ncol=3)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(folder / "fig_bias_modelrec.pdf")
    plt.close(fig)


def main():
    df = rows()
    figures(df, Path(__file__).resolve().parent / "report")
    print(f"{df.groupby('scenario')[['gen', 'it']].apply(lambda g: len(g.drop_duplicates())).to_dict()} participants "
          f"(paired), {BUDGET} trials per condition")
    own = df[df.model == df.gen]
    for p, variant in (("c1", "bias"), ("c2", "bias"), ("d", "bias"), ("d", "d")):
        print(f"\n== {p} ({'c_low' if p == 'c1' else 'c_high' if p == 'c2' else 'd'}), "
              f"{'c and d free' if variant == 'bias' else 'd only'}, generating model ==")
        print(own[own.variant == variant].groupby(["scenario", "gen"]).apply(rec, p, "t_" + p).round(2).to_string())
    print("\n== model recovery (AIC), % correct ==")
    for name, sel in (("no bias", ["nobias"]), ("d only", ["d"]), ("c and d", ["bias"]), ("best of all", ["nobias", "d", "bias"])):
        s = df[df.variant.isin(sel)]
        best = s.loc[s.groupby(["scenario", "gen", "it"]).aic.idxmin()]
        hit = (best.model == best.gen)
        t = hit.groupby([best.scenario, best.gen]).mean().unstack()
        t["all"] = hit.groupby(best.scenario).mean()
        print(f"{name}:\n{(100 * t).round(0).to_string()}")
    print("\n== p_c (CI participants, CI fit) ==")
    ci = own[own.gen == "ci"]
    print(ci.groupby(["scenario", "variant"]).apply(rec, "pc", "t_pc").round(3).to_string())


if __name__ == "__main__":
    main()
